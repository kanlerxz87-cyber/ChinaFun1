def video_links(videos):
    if not videos:
        return '<span class="unv">no verified link</span>'
    out = []
    for v in videos:
        tag = {"youtube": "YT", "tiktok": "TT", "instagram": "IG"}.get(v.get("platform", ""), v.get("platform", "link")[:2].upper())
        out.append(f'<a class="vbtn {esc(v.get("platform",""))}" href="{esc(v["url"])}" target="_blank" rel="noopener" title="{esc(v.get("title",""))}">{tag}</a>')
    return " ".join(out)


def video_bank(rests, acts):
    rows = []
    for it in list(rests) + list(acts):
        for v in it.get("videos", []) or []:
            rows.append([esc(it.get("name", "")), esc(v.get("platform", "")), f'<a href="{esc(v["url"])}" target="_blank" rel="noopener">{esc(v.get("title", v["url"]))}</a>', esc(v.get("meta", ""))])
    return table(["Place","Platform","Link","Detail"], rows, table_id="videos") if rows else '<p class="muted">Pending.</p>'


def pre_table(rests):
    def tier_order(r):
        return {"3": 3, "2": 2, "1": 1}.get(r.get("tier"), 0)

    rows = []
    for r in sorted(rests, key=lambda x: (-tier_order(x), x.get("name", ""))):
        if r.get("tier") not in ("3", "2", "1"):
            continue
        stars = {"3": "★★★", "2": "★★", "1": "★"}[r["tier"]]
        price = r.get("price_two_adults", {}) or {}
        if price.get("usd"):
            ptxt = money(price["usd"]) + '<br><span class="muted">' + esc(price.get("basis", "")) + "</span>"
        elif price.get("range"):
            ptxt = esc(price["range"]) + '<br><span class="muted">' + esc(price.get("basis", "")) + "</span>"
        else:
            ptxt = '<span class="unv">not published</span><br><span class="muted">' + esc(price.get("basis", "")) + "</span>"
        hrs = r.get("hours", {}) or {}
        htxt = esc(hrs.get("text", "")) if hrs.get("text") else '<span class="unv">—</span>'
        closed = esc(hrs.get("closed", "")) if hrs.get("closed") else '<span class="unv">—</span>'
        name_cell = "<strong>" + esc(r["name"]) + "</strong>"
        if r.get("name_local"):
            name_cell += '<br><span class="muted">' + esc(r["name_local"]) + "</span>"
        addr = esc(r.get("address", ""))
        links = ""
        if r.get("michelin_url"):
            links += '<a href="' + esc(r["michelin_url"]) + '" target="_blank" rel="noopener">Michelin</a>'
        if r.get("official_url"):
            links += (' · ' if links else "") + '<a href="' + esc(r["official_url"]) + '" target="_blank" rel="noopener">site</a>'
        links += '<br><span class="muted">src ' + src_links(r.get("sources")) + "</span>"
        rows.append([
            name_cell + '<br><span class="muted">' + addr + "</span>",
            '<span class="stars">' + stars + '</span><br><span class="muted">' + esc(r.get("tier_label", "")) + "</span>",
            esc(r.get("cuisine", "")),
            esc(r.get("district", "")),
            esc(r.get("price_band", "")) or '<span class="unv">—</span>',
            ptxt,
            htxt,
            closed,
            video_links(r.get("videos")),
            links,
        ])
    return table(["Restaurant & address", "MICHELIN", "Cuisine", "District", "Price band", "Cost for 2 adults", "Open (days / hours)", "Closed / exceptions", "Watch", "Links"], rows, table_id="michelin")


