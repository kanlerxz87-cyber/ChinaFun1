def load(name, default=None):
    p = os.path.join(DATA, name)
    if not os.path.exists(p):
        return default if default is not None else []
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def esc(v):
    return html.escape("" if v is None else str(v))


def haversine_km(a, b):
    if not a or not b or a[0] is None or b[0] is None:
        return None
    lat1, lon1, lat2, lon2 = map(math.radians, [a[0], a[1], b[0], b[1]])
    dlat, dlon = lat2 - lat1, lon2 - lon1
    h = math.sin(dlat / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2) ** 2
    return 6371.0088 * 2 * math.asin(math.sqrt(h))


def est_transit_min(km, method):
    """Documented ESTIMATE model (see sources.html#method). Not a measured journey time."""
    if km is None:
        return None
    walk_wait = method.get("walk_wait_min", 16)      # access + egress + platform wait
    detour = method.get("detour_factor", 1.3)         # street/metro routing vs straight line
    min_per_km = method.get("min_per_km", 2.5)        # ~24 km/h effective incl. dwell time
    return round(walk_wait + km * detour * min_per_km)


def money(v, cur="USD"):
    if v in (None, ""):
        return ""
    try:
        return f"{cur} {float(v):,.0f}"
    except (TypeError, ValueError):
        return esc(v)


def badge(text, kind=""):
    return f'<span class="tag {kind}">{esc(text)}</span>'


def src_links(sources):
    out = []
    for i, s in enumerate(sources or [], 1):
        label = s.get("label") or s.get("type") or "source"
        url = s.get("url", "")
        when = s.get("checked", "")
        title = f'{label}{" — checked " + when if when else ""}'
        out.append(f'<a href="{esc(url)}" target="_blank" rel="noopener" title="{esc(title)}">{i}</a>')
    return " ".join(out) if out else '—'


def nm(v):
    return f'<span class="unv">—</span>' if v in (None, "", "unverified") else esc(v)


def table(headers, rows, cls="", table_id=""):
    h = "".join(f"<th>{x}</th>" for x in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    idattr = f' id="{table_id}"' if table_id else ""
    return f'<div class="tablewrap"><table class="{cls}"{idattr}><thead><tr>{h}</tr></thead><tbody>{body}</tbody></table></div>'


