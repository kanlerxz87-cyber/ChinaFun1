def kpi(label, value, note=""):
    return f'<div class="kpi"><div class="kpi-l">{esc(label)}</div><div class="kpi-v">{value}</div><div class="kpi-n">{note}</div></div>'


def card(title, inner, cls=""):
    return f'<section class="card {cls}"><h2>{title}</h2>{inner}</section>'


