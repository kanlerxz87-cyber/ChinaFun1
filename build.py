def hotel_top_table(hotels):
    if not hotels:
        return '<p class="muted">Pending.</p>'
    rows = [[f'<strong>{esc(h["name"])}</strong>', str(len(h["_within60"])), str(h["_star_sum"]),
             money(next(iter(h.get("price", {}).values()), {}).get("total_usd")),
             src_links(h.get("sources")[:1])] for h in hotels]
    return table(["Hotel","≤60 min starred","Star weight","7-night total","Source"], rows)


def hotel_alt_prices(hotels):
    rows = []
    for h in sorted(hotels, key=lambda x: x.get("name", "")):
        for a in h.get("alt_prices", []) or []:
            rows.append([f'<strong>{esc(h["name"])}</strong>', esc(a.get("window", "")), money(a.get("total_usd")), esc(a.get("note", ""))])
    if not rows:
        return '<p class="muted">None captured.</p>'
    return table(["Hotel", "Window / room", "Total (2 adults)", "Note"], rows, table_id="altprices")


def hotel_price_detail(hotels, windows):
    rows = []
    for h in sorted(hotels, key=lambda x: x.get("name", "")):
        p = h.get("price", {}).get("w1", {})
        if p.get("total_usd"):
            url = p.get("url", "")
            src = '<a href="' + esc(url) + '" target="_blank" rel="noopener">Booking.com</a>' if url else "—"
            rows.append([
                "<strong>" + esc(h["name"]) + "</strong><br><span class=\"muted\">" + esc(h.get("district", "")) + "</span>",
                esc(p.get("room_type", "")),
                esc(p.get("bed", "")),
                money(p.get("total_usd")),
                esc(p.get("note", "")),
                src,
            ])
        else:
            alt = "; ".join(a.get("window", "") + " → " + money(a.get("total_usd")) for a in (h.get("alt_prices") or [])[:2])
            rows.append([
                "<strong>" + esc(h["name"]) + "</strong><br><span class=\"muted\">" + esc(h.get("district", "")) + "</span>",
                '<span class="unv">no W1 rate</span>',
                "—", '<span class="unv">unavailable</span>',
                "Not bookable for 15–22 Feb 2027 on Booking.com" + ((" · adjacent dates: " + alt) if alt else ""),
                "—",
            ])
    return table(["Hotel", "Cheapest qualifying room (W1)", "Bed", "7-night total, 2 adults", "Rate terms", "Source"], rows, table_id="pricedetail")


def window_sweep():
    rows = []
    for w in load("window_pricing.json", []):
        src = w.get("source", {})
        rows.append([esc(w.get("window_id", "")), esc(w.get("checkin", "")), esc(w.get("checkout", "")),
                     money(w.get("per_night_usd")), money(w.get("total_usd")),
                     esc(w.get("note", "")), src_links([src] if src else [])])
    if not rows:
        return '<p class="muted">Pending.</p>'
    return table(["Window", "Check-in", "Check-out", "Per night", "7-night total (2 adults)", "What the rate is", "Source"], rows, table_id="sweep")


def cluster_table(hotels):
    rows = []
    for h in sorted(hotels, key=lambda x: -len(x["_within60"])):
        items = "<br>".join(f'{"★" * int(x["tier"])} {esc(x["name"])} — {x["km"]} km / ~{x["min"]} min' for x in h["_within60"][:12]) or '<span class="unv">none</span>'
